"""This command is used to aggregate all the individual files that readers creates while recording data into a single 'data.npy' file. 


You want to run this process to clean data. Since readers can quickly generate thousands of files, moving them can be very slow. This procedure will reduce the number of files by aggregating their data into a single file. 

Important: 
    The aggregation is realized PER reader and PER recording. 

This program will first aggregate the data from the fresh measurements and also from older, saved measurements. If a recording has already been aggregated, it will be ignored.é
"""
import os
from pathlib import Path
from typing import Dict, List, Tuple
import numpy as np
import matplotlib.pyplot as plt
import configparser
import argparse
import json


import logging

logger = logging.getLogger(__name__)
from labpilot.scripting import list_experiment_folders, read_data

# Setup arguments
parser = argparse.ArgumentParser(
    description="SNAPSHOT Results Aggregations: Use this software to aggregate the results into a single file and gain time later. You can also generate gluing reports."
)

parser.add_argument(
    "-c",
    "--config",
    type=str,
    required=True,
    help="Location of the configuration file to use. It must be the same as the main SNAPSHOT interface",
)

parser.add_argument(
    "-a",
    "--all",
    required=False,
    default=False,
    action="store_true",
    help="If this argument is given, this will go over all the recordings and perform the aggregation",
)

parser.add_argument(
    "-f",
    "--folder",
    required=False,
    default=None,
    type=str,
    help="path to the recording/base folder",
)

# args = parser.parse_args()


def aggregate(
    base_path: str, zip_save: bool = True, delete_detail_outputs: bool = True
):
    """Aggregate all the files that are present inside a given directory.

    This function will go over all subdirectories to detect the different experiments and aggregate all the data files generated by the readers

    Args:
        base_path (str): Path where measurement folders will be search recursively
        zip_save (bool, optional): If `True`, all detail output files (output_xx.npy) will be saved into a ZIP file. If `False`, the ZIP file will be deleted if it exists.
        delete_detail_outputs (bool, optional): If `True`, all detail output files (output_xx.npy) will be deleted after the aggragation if it was successful
    """
    experiment_folders = list_experiment_folders(base_path)

    _aggregate(
        experiment_folders,
        zip_save=zip_save,
        delete_detail_outputs=delete_detail_outputs,
    )


def _aggregate(
    experiment_folders: List[str] | List[Path],
    zip_save: bool = True,
    delete_detail_outputs: bool = True,
):
    """Aggregate the measurement data

    Args:
        experiment_folders (List[str]): List of measurement folders that need to be aggregated
        zip_save (bool, optional): If `True`, all detail output files (output_xx.npy) will be saved into a ZIP file. If `False`, the ZIP file will be deleted if it exists.
        delete_detail_outputs (bool, optional): If `True`, all detail output files (output_xx.npy) will be deleted after the aggragation if it was successful
    """
    # Go in each folder
    for experiment_path in experiment_folders:
        logger.info(f"Treating recordings in: {experiment_path}")
        for folder in os.listdir(experiment_path):
            recording_path = os.path.join(experiment_path, folder)
            # Check that this is a folder
            if os.path.isdir(recording_path):
                # If it possesses an info.json file, it means it's a recording
                if "info.json" in os.listdir(recording_path):
                    # all folder in a recording path corresponds to a measurement
                    for instrument in os.listdir(recording_path):
                        if not os.path.isdir(os.path.join(recording_path, instrument)):
                            continue
                        path_template = os.path.join(
                            recording_path, instrument, "output_%1.npy"
                        )
                        logger.info(f"Reading {folder}.{instrument}:")
                        data = read_data(
                            path_template,
                            zip_save=zip_save,
                            delete_detail_outputs=delete_detail_outputs,
                        )
